// ---- Crawl state ----
let crawlState = { status: "idle", logs: [], error: null };
let sseClients = [];

function broadcast(line) {
  crawlState.logs.push(line);
  const data = `data: ${JSON.stringify({ line })}\n\n`;
  sseClients.forEach((res) => res.write(data));
}

function writeConfig(settings) {
  const { baseURL, auth, maxPages, maxDepth, seedPaths } = settings;
  const authBlock = buildAuthBlock(auth);
  const parsedSeedPaths = seedPaths
    ? seedPaths.split("\n").map(p => p.trim()).filter(p => p.startsWith("/"))
    : [];

  const content = `// config.js — auto-generated by the UI
export default {
  baseURL: ${JSON.stringify(baseURL)},
  crawl: {
    maxPages: ${maxPages || 30},
    maxDepth: ${maxDepth || 5},
    waitAfterAction: 500,
    seedPaths: ${JSON.stringify(parsedSeedPaths)}
  },
  auth: ${authBlock},
  output: {
    rawDir: "tests/generated/site-maps/raw",
    summaryFile: "tests/generated/site-maps/crawl-summary.json"
  }
};
`;
  fs.writeFileSync(path.join(ROOT, "config.js"), content, "utf-8");
}

function buildAuthBlock(auth) {
  if (!auth || auth.type === "none") return `{ type: "none" }`;
  if (auth.type === "form") {
    return `{
    type: "form",
    loginURL: ${JSON.stringify(auth.loginURL || "/login")},
    usernameSelector: ${JSON.stringify(auth.usernameSelector || "#email")},
    passwordSelector: ${JSON.stringify(auth.passwordSelector || "#password")},
    submitSelector: ${JSON.stringify(auth.submitSelector || "#login-button")},
    username: process.env.TEST_USERNAME || ${JSON.stringify(auth.username || "")},
    password: process.env.TEST_PASSWORD || ${JSON.stringify(auth.password || "")},
    successURLContains: ${JSON.stringify(auth.successURLContains || "/dashboard")}
  }`;
  }
  if (auth.type === "bearer") {
    return `{
    type: "bearer",
    bearerToken: process.env.TEST_BEARER_TOKEN || ${JSON.stringify(auth.bearerToken || "")}
  }`;
  }
  if (auth.type === "cookie") {
    return `{
    type: "cookie",
    cookie: {
      name: ${JSON.stringify(auth.cookieName || "session_id")},
      value: process.env.TEST_SESSION_COOKIE || ${JSON.stringify(auth.cookieValue || "")},
      domain: ${JSON.stringify(auth.cookieDomain || "")}
    }
  }`;
  }
  return `{ type: "none" }`;
}

function writeFuzzConfig(baseURL) {
  const content = `// config.js — auto-generated by fuzzer UI
export default {
  baseURL: ${JSON.stringify(baseURL)},
  crawl: {
    maxPages: 30,
    maxDepth: 5,
    waitAfterAction: 500,
    seedPaths: []
  },
  auth: { type: "none" },
  output: {
    rawDir: "tests/generated/site-maps/raw",
    summaryFile: "tests/generated/site-maps/crawl-summary.json"
  }
};
`;
  fs.writeFileSync(path.join(ROOT, "config.js"), content, "utf-8");
}

// ---- Crawl routes ----
app.post("/api/crawl", (req, res) => {
  if (crawlState.status === "crawling") {
    return res.status(409).json({ error: "A crawl is already running" });
  }
  const settings = req.body;
  if (!settings.baseURL) {
    return res.status(400).json({ error: "baseURL is required" });
  }
  crawlState = { status: "crawling", logs: [], error: null };
  try {
    writeConfig(settings);
  } catch (err) {
    crawlState.status = "error";
    return res.status(500).json({ error: err.message });
  }
  const child = spawn("node", ["crawler/index.js"], { cwd: ROOT, env: { ...process.env } });
  child.stdout.on("data", (data) => data.toString().split("\n").filter(Boolean).forEach(broadcast));
  child.stderr.on("data", (data) => data.toString().split("\n").filter(Boolean).forEach((l) => broadcast(`[stderr] ${l}`)));
  child.on("close", (code) => {
    crawlState.status = code === 0 ? "done" : "error";
    broadcast(code === 0 ? "[crawl complete]" : `[crawl failed: exit code ${code}]`);
    sseClients.forEach((c) => c.write(`event: done\ndata: ${JSON.stringify({ status: crawlState.status })}\n\n`));
    sseClients = [];
  });
  res.json({ message: "Crawl started" });
});

app.get("/api/crawl/stream", (req, res) => {
  res.setHeader("Content-Type", "text/event-stream");
  res.setHeader("Cache-Control", "no-cache");
  res.setHeader("Connection", "keep-alive");
  res.flushHeaders();
  crawlState.logs.forEach((line) => res.write(`data: ${JSON.stringify({ line })}\n\n`));
  if (crawlState.status === "done" || crawlState.status === "error") {
    res.write(`event: done\ndata: ${JSON.stringify({ status: crawlState.status })}\n\n`);
    res.end();
    return;
  }
  sseClients.push(res);
  req.on("close", () => { sseClients = sseClients.filter((c) => c !== res); });
});

app.get("/api/crawl/status", (req, res) => {
  res.json({ status: crawlState.status, logCount: crawlState.logs.length, error: crawlState.error });
});

