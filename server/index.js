// ---- Standalone data regeneration ----
app.post("/api/generate-data", async (req, res) => {
  try {
    const { generateTestData } = await import("../generator/data.js");
    const casesDir = path.join(ROOT, "tests/generated/test-cases");
    const dataDir = path.join(ROOT, "tests/generated/test-data");
    const rawDir = path.join(ROOT, "tests/generated/site-maps/raw");

    if (!fs.existsSync(casesDir)) {
      return res.status(400).json({ error: "No test cases found. Run the generator first." });
    }

    const allCases = {};
    fs.readdirSync(casesDir).filter(f => f.endsWith(".json")).forEach(file => {
      try {
        const data = JSON.parse(fs.readFileSync(path.join(casesDir, file), "utf-8"));
        allCases[data.feature] = data.cases;
      } catch {}
    });

    const allData = generateTestData(allCases, rawDir);

    fs.mkdirSync(dataDir, { recursive: true });
    for (const [feature, cases] of Object.entries(allCases)) {
      const featureData = {};
      cases.forEach(tc => { if (allData[tc.id]) featureData[tc.id] = allData[tc.id]; });
      const filename = feature.toLowerCase().replace(/\s+/g, "-").replace(/[^a-z0-9-]/g, "") + ".data.json";
      fs.writeFileSync(path.join(dataDir, filename), JSON.stringify({ feature, data: featureData }, null, 2));
    }

    res.json({
      message: "Test data regenerated",
      count: Object.keys(allData).filter(k => allData[k] !== null).length
    });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

